"""Generate a Python config reader from an env file's variable names."""

import argparse
import re
from pathlib import Path


ENV_ASSIGNMENT = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=")


def read_env_keys(env_file: Path) -> list[str]:
    keys = []
    seen = set()

    with env_file.open(encoding="utf-8") as file:
        for line_number, line in enumerate(file, start=1):
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue

            match = ENV_ASSIGNMENT.match(line)
            if match is None:
                raise ValueError(
                    f"{env_file}:{line_number}: expected an ENV_VAR=value assignment"
                )

            key = match.group(1)
            if key not in seen:
                keys.append(key)
                seen.add(key)

    if not keys:
        raise ValueError(f"{env_file}: no environment variable assignments found")

    return keys


def render_config_module(keys: list[str]) -> str:
    entries = "\n".join(f'        "{key}": os.getenv("{key}"),' for key in keys)
    return (
        '"""Generated by scripts/generate_env_config.py. Do not edit manually."""\n'
        "\n"
        "import os\n"
        "from dotenv import load_dotenv\n"
        "\n"
        "\n"
        "def get_config() -> dict[str, str | None]:\n"
        '    """Load the local .env file and return the declared settings."""\n'
        "    load_dotenv()\n"
        "    return {\n"
        f"{entries}\n"
        "    }\n"
    )


def generate_config(env_file: Path, output_file: Path) -> list[str]:
    if env_file.resolve() == output_file.resolve():
        raise ValueError("The input env file and output Python file must be different.")

    keys = read_env_keys(env_file)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(render_config_module(keys), encoding="utf-8")
    return keys


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate a Python config reader without embedding env values."
    )
    parser.add_argument(
        "--env-file",
        type=Path,
        default=Path(".env.example"),
        help="File whose variable names define the generated config (default: .env.example)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("src/generated_config.py"),
        help="Python module to write (default: src/generated_config.py)",
    )
    args = parser.parse_args()

    keys = generate_config(args.env_file, args.output)
    print(f"Generated {args.output} with {len(keys)} environment variable(s).")


if __name__ == "__main__":
    main()
